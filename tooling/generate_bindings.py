#!/usr/bin/env python3
"""Generate the low-level ctypes binding from SonyHeadphonesClient's C ABI."""

from __future__ import annotations

import argparse
import ast
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path


GENERATED_NOTICE = """\
\"\"\"Generated from SonyHeadphonesClient

Do not edit this file directly; run ``python tooling/generate_bindings.py``.
\"\"\"

from __future__ import annotations
"""

INTEGER_CTYPES = {
    "char": "c_char",
    "int": "c_int",
    "int8_t": "c_int8",
    "uint8_t": "c_uint8",
    "int16_t": "c_int16",
    "uint16_t": "c_uint16",
    "int32_t": "c_int32",
    "uint32_t": "c_uint32",
    "int64_t": "c_int64",
    "uint64_t": "c_uint64",
    "unsigned char": "c_uint8",
}


@dataclass(frozen=True)
class Field:
    name: str
    c_type: str
    array_size: int | None = None
    callback_args: tuple[str, ...] | None = None


@dataclass(frozen=True)
class Struct:
    name: str
    fields: tuple[Field, ...]


@dataclass(frozen=True)
class Function:
    name: str
    result: str
    arguments: tuple[str, ...]


C_STRING_LITERAL = r'"(?:[^"\\\n]|\\.)*"'
C_LITERAL_OR_COMMENT = re.compile(
    r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'|/\*.*?\*/|//[^\n]*',
    flags=re.DOTALL,
)


def strip_comments(source: str) -> str:
    """Splice C logical lines, then remove comments without damaging literals."""
    source = re.sub(r"\\\r?\n", "", source)

    def replace(match: re.Match[str]) -> str:
        token = match.group()
        if token.startswith(("/*", "//")):
            # Comments separate tokens; keep line boundaries for anchored parsers.
            return " " + "\n" * token.count("\n")
        return token

    return C_LITERAL_OR_COMMENT.sub(replace, source)


def split_arguments(arguments: str) -> list[str]:
    parts: list[str] = []
    start = 0
    depth = 0
    for index, char in enumerate(arguments):
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(arguments[start:index].strip())
            start = index + 1
    tail = arguments[start:].strip()
    if tail and tail != "void":
        parts.append(tail)
    return parts


def parse_declaration(declaration: str) -> tuple[str, str, int | None]:
    declaration = " ".join(declaration.strip().split())
    match = re.fullmatch(r"(.+?)([A-Za-z_]\w*)\s*(?:\[\s*(\d+)\s*\])?", declaration)
    if not match:
        raise ValueError(f"unsupported declaration: {declaration!r}")
    c_type = match.group(1).strip()
    name = match.group(2)
    array_size = int(match.group(3)) if match.group(3) else None
    return c_type, name, array_size


def argument_type(declaration: str) -> str:
    c_type, _, array_size = parse_declaration(declaration)
    if array_size is not None:
        c_type += "*"
    return c_type


def parse_structs(source: str) -> list[Struct]:
    structs: list[Struct] = []
    pattern = re.compile(
        r"typedef\s+struct\s+(\w+)\s*\{(.*?)\}\s*(\w+)\s*;",
        flags=re.DOTALL,
    )
    for tag, body, typedef_name in pattern.findall(source):
        if tag != typedef_name:
            raise ValueError(f"struct tag {tag} does not match typedef {typedef_name}")
        fields: list[Field] = []
        for declaration in body.split(";"):
            declaration = declaration.strip()
            if not declaration:
                continue
            callback = re.fullmatch(r"(.+?)\(\s*\*\s*(\w+)\s*\)\s*\((.*)\)", declaration, re.DOTALL)
            if callback:
                args = tuple(argument_type(arg) for arg in split_arguments(callback.group(3)))
                fields.append(
                    Field(
                        name=callback.group(2),
                        c_type=callback.group(1).strip(),
                        callback_args=args,
                    )
                )
                continue
            c_type, name, array_size = parse_declaration(declaration)
            fields.append(Field(name, c_type, array_size))
        structs.append(Struct(typedef_name, tuple(fields)))
    return structs


def parse_callbacks(source: str) -> list[Function]:
    callbacks: list[Function] = []
    pattern = re.compile(
        r"^[ \t]*typedef\s+([^;{}()]+?)\(\s*\*\s*(\w+)\s*\)\s*\((.*?)\)\s*;",
        flags=re.DOTALL | re.MULTILINE,
    )
    for result, name, arguments in pattern.findall(source):
        callbacks.append(
            Function(
                name,
                " ".join(result.split()),
                tuple(argument_type(arg) for arg in split_arguments(arguments)),
            )
        )
    return callbacks


def parse_functions(source: str) -> list[Function]:
    functions: list[Function] = []
    pattern = re.compile(
        r"^[ \t]*MDR_API\b\s+([^;{}()]+?)(?<!\w)(mdr\w+)\s*\((.*?)\)\s*;",
        flags=re.DOTALL | re.MULTILINE,
    )
    for result, name, arguments in pattern.findall(source):
        functions.append(
            Function(
                name,
                " ".join(result.split()),
                tuple(argument_type(arg) for arg in split_arguments(arguments)),
            )
        )
    return functions


def parse_integer_aliases(source: str) -> dict[str, str]:
    aliases: dict[str, str] = {}
    for base, name in re.findall(
        r"typedef\s+(u?int(?:8|16|32|64)_t)\s+(MDR\w+)\s*;",
        source,
    ):
        aliases[name] = base
    return aliases


def parse_opaque_structs(source: str) -> set[str]:
    return set(re.findall(r"typedef\s+struct\s+(\w+)\s+\1\s*;", source))


def ctype_expression(
    c_type: str,
    aliases: dict[str, str],
    struct_names: set[str],
    opaque_structs: set[str],
) -> str:
    c_type = " ".join(c_type.replace("*", " * ").split())
    c_type = re.sub(r"\bconst\b", "", c_type)
    c_type = " ".join(c_type.split())
    pointer_count = c_type.split().count("*")
    base = c_type.replace("*", "").strip()

    if base == "void" and pointer_count == 0:
        return "None"
    if base == "void":
        expression = "c_void_p"
        pointer_count -= 1
    elif base == "char" and pointer_count:
        expression = "c_char_p"
        pointer_count -= 1
    elif base in opaque_structs and pointer_count:
        expression = "c_void_p"
        pointer_count -= 1
    elif base in aliases:
        expression = base
    elif base in INTEGER_CTYPES:
        expression = INTEGER_CTYPES[base]
    elif base in struct_names:
        expression = base
    else:
        raise ValueError(f"unsupported C type: {c_type!r}")

    for _ in range(pointer_count):
        expression = f"POINTER({expression})"
    return expression


def callback_name(struct_name: str, field_name: str) -> str:
    return f"{struct_name}{field_name[0].upper()}{field_name[1:]}"


def render_api(headers: list[str]) -> str:
    source = strip_comments("\n".join(headers))
    if re.search(
        r"^[ \t]*#[ \t]*pragma[ \t]+(?:pack|ms_struct|scalar_storage_order)\b|\b_Pragma\s*\(",
        source,
        flags=re.MULTILINE,
    ):
        raise ValueError("ABI layout pragmas require explicit ctypes layout support")
    aliases = parse_integer_aliases(source)
    structs = parse_structs(source)
    callbacks = parse_callbacks(source)
    functions = parse_functions(source)
    struct_names = {struct.name for struct in structs}
    opaque_structs = parse_opaque_structs(source)
    named_types = struct_names | {callback.name for callback in callbacks}
    parsed_typedefs = len(aliases) + len(structs) + len(callbacks) + len(opaque_structs)
    if parsed_typedefs != len(re.findall(r"\btypedef\b", source)):
        raise ValueError("unsupported or duplicate typedef in ABI headers")
    if len(functions) != len(re.findall(r"^[ \t]*MDR_API\b", source, flags=re.MULTILINE)):
        raise ValueError("unsupported MDR_API declaration in ABI headers")

    def ct(c_type: str) -> str:
        return ctype_expression(c_type, aliases, named_types, opaque_structs)

    lines = [
        GENERATED_NOTICE.rstrip(),
        "",
        "from ctypes import (",
        "    CFUNCTYPE,",
        "    POINTER,",
        "    Structure,",
        "    c_char,",
        "    c_char_p,",
        "    c_int,",
        "    c_int8,",
        "    c_int16,",
        "    c_int32,",
        "    c_int64,",
        "    c_uint8,",
        "    c_uint16,",
        "    c_uint32,",
        "    c_uint64,",
        "    c_void_p,",
        ")",
        "",
    ]
    for name, base in aliases.items():
        lines.append(f"{name} = {INTEGER_CTYPES[base]}")
    lines.append("")

    for struct in structs:
        lines.extend([f"class {struct.name}(Structure):", "    pass", ""])
        for field in struct.fields:
            if field.callback_args is not None:
                args = ", ".join(ct(arg) for arg in field.callback_args)
                suffix = f", {args}" if args else ""
                lines.append(
                    f"{callback_name(struct.name, field.name)} = "
                    f"CFUNCTYPE({ct(field.c_type)}{suffix})"
                )
        if any(field.callback_args is not None for field in struct.fields):
            lines.append("")
        lines.append(f"{struct.name}._fields_ = [")
        for field in struct.fields:
            if field.callback_args is not None:
                expression = callback_name(struct.name, field.name)
            else:
                expression = ct(field.c_type)
                if field.array_size is not None:
                    expression = f"{expression} * {field.array_size}"
            lines.append(f'    ("{field.name}", {expression}),')
        lines.extend(["]", ""])

    for callback in callbacks:
        args = ", ".join(ct(arg) for arg in callback.arguments)
        suffix = f", {args}" if args else ""
        lines.extend([f"{callback.name} = CFUNCTYPE({ct(callback.result)}{suffix})", ""])

    lines.extend(["", "def bind(lib: object) -> None:"])
    for function in functions:
        arguments = ", ".join(ct(arg) for arg in function.arguments)
        lines.append(f"    lib.{function.name}.argtypes = [{arguments}]")
        lines.append(f"    lib.{function.name}.restype = {ct(function.result)}")
    lines.append("")
    return "\n".join(lines)


def safe_integer(expression: str, known: dict[str, int] | None = None) -> int:
    expression = re.sub(r"\b(0[xX][0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", expression.strip())
    tree = ast.parse(expression, mode="eval")
    known = known or {}
    operators = {
        ast.BitOr: lambda left, right: left | right,
        ast.BitAnd: lambda left, right: left & right,
        ast.BitXor: lambda left, right: left ^ right,
        ast.Mult: lambda left, right: left * right,
        ast.LShift: lambda left, right: left << right,
        ast.RShift: lambda left, right: left >> right,
        ast.Add: lambda left, right: left + right,
        ast.Sub: lambda left, right: left - right,
    }

    def evaluate(node: ast.AST) -> int:
        if isinstance(node, ast.Expression):
            return evaluate(node.body)
        if isinstance(node, ast.Constant) and isinstance(node.value, int):
            return node.value
        if isinstance(node, ast.Name) and node.id in known:
            return known[node.id]
        if isinstance(node, ast.BinOp) and type(node.op) in operators:
            return operators[type(node.op)](evaluate(node.left), evaluate(node.right))
        if isinstance(node, ast.UnaryOp):
            value = evaluate(node.operand)
            if isinstance(node.op, ast.UAdd):
                return value
            if isinstance(node.op, ast.USub):
                return -value
            if isinstance(node.op, ast.Invert):
                return ~value
        raise ValueError(f"unsupported integer expression: {expression!r}")

    return evaluate(tree)


def macro_value(expression: str, known: dict[str, int] | None = None) -> int | str | None:
    expression = expression.strip()
    if re.fullmatch(rf"(?:{C_STRING_LITERAL}\s*)+", expression):
        return "".join(ast.literal_eval(lit) for lit in re.findall(C_STRING_LITERAL, expression))
    cast = re.fullmatch(r"\(\s*\(\s*[A-Za-z_]\w*\s*\)\s*(.+)\)", expression)
    if cast:
        expression = cast.group(1)
    try:
        return safe_integer(expression, known)
    except (SyntaxError, ValueError):
        return None


def parse_macros(source: str) -> list[tuple[str, int | str]]:
    source = strip_comments(source)
    definitions: dict[str, str] = {}
    pattern = r"^[ \t]*#[ \t]*define[ \t]+(MDR_\w+)\b([^\n]*)$"
    for name, tail in re.findall(pattern, source, flags=re.MULTILINE):
        # Export decorations and function-like macros are not Python constants.
        if name == "MDR_API" or tail.startswith("("):
            continue
        expression = tail.strip()
        if not expression:
            raise ValueError(f"empty ABI constant: {name}")
        if name in definitions:
            raise ValueError(f"duplicate ABI constant: {name}")
        definitions[name] = expression

    values: dict[str, int | str] = {}
    known: dict[str, int] = {}
    pending = dict(definitions)
    while pending:
        resolved: list[str] = []
        for name, expression in pending.items():
            value = macro_value(expression, known)
            if value is not None:
                values[name] = value
                if isinstance(value, int):
                    known[name] = value
                resolved.append(name)
        if not resolved:
            details = ", ".join(f"{name}={expression!r}" for name, expression in pending.items())
            raise ValueError(f"unsupported or unresolved ABI constant(s): {details}")
        for name in resolved:
            del pending[name]
    return [(name, values[name]) for name in definitions]


def python_constant_name(c_name: str, *, results: bool = False) -> str:
    name = c_name.removeprefix("MDR_")
    if results:
        name = name.removeprefix("RESULT_")
    return name


def render_constants(source: str, *, results: bool = False, trailer: list[str] | None = None) -> str:
    lines = [GENERATED_NOTICE.rstrip(), ""]
    for c_name, value in parse_macros(strip_comments(source)):
        name = python_constant_name(c_name, results=results)
        lines.append(f"{name} = {value!r}")
    lines.extend(trailer or ())
    lines.append("")
    return "\n".join(lines)


def parse_i18n_strings(source: str) -> dict[str, str]:
    """``_Def(TextId, "text")`` entries from a client/I18N locale file."""
    source = strip_comments(source)
    strings: dict[str, str] = {}
    pattern = re.compile(rf"\b_Def\s*\(\s*(\w+)\s*,\s*((?:{C_STRING_LITERAL}\s*)+)\)")
    # Mask literal contents so examples of _Def inside text are not treated as calls.
    masked = C_LITERAL_OR_COMMENT.sub(lambda match: " " * len(match.group()), source)
    for call in re.finditer(r"\b_Def\s*\(", masked):
        match = pattern.match(source, call.start())
        if match is None:
            raise ValueError(f"unsupported _Def entry near {source[call.start():call.start() + 100]!r}")
        text_id, literals = match.groups()
        if text_id in strings:
            raise ValueError(f"duplicate _Def entry: {text_id}")
        strings[text_id] = "".join(ast.literal_eval(lit) for lit in re.findall(C_STRING_LITERAL, literals))
    return strings


def parse_feature_text_ids(source: str) -> dict[str, str]:
    """``MDR_FEATURE_*`` -> ``i18n::TextId`` from the client's ``kFeatures`` table."""
    source = strip_comments(source)
    table = re.search(r"\bkFeatures\s*\[\s*\]\s*=\s*\{(.*?)\}\s*;", source, flags=re.DOTALL)
    if not table:
        raise ValueError("kFeatures table not found in client source")
    row_pattern = re.compile(
        r"\{\s*i18n\s*::\s*TextId\s*::\s*(\w+)\s*,\s*(MDR_FEATURE_\w+)\s*,?\s*\}"
    )
    body = table.group(1)
    if row_pattern.sub("", body).strip(" \t\r\n,"):
        raise ValueError("unsupported row in kFeatures table")
    text_ids: dict[str, str] = {}
    for text_id, feature in row_pattern.findall(body):
        if feature in text_ids:
            raise ValueError(f"duplicate kFeatures row: {feature}")
        text_ids[feature] = text_id
    return text_ids


def render_feature_names(headphones: str, client: str, strings_source: str) -> list[str]:
    features = [
        name
        for name, value in parse_macros(strip_comments(headphones))
        if name.startswith("MDR_FEATURE_") and not name.endswith("_MAX_VALUE") and isinstance(value, int)
    ]
    text_ids = parse_feature_text_ids(client)
    strings = parse_i18n_strings(strings_source)

    lines = [
        "",
        "# Display names: client/Client.cpp kFeatures -> client/I18N/Default.cpp.",
        "FEATURE_NAMES = {",
    ]
    for c_name in features:
        text_id = text_ids.get(c_name)
        if text_id is None:
            label = c_name.removeprefix("MDR_FEATURE_").replace("_", " ").capitalize()
            print(f"note: {c_name} is not in kFeatures; using {label!r}", file=sys.stderr)
        elif text_id in strings:
            label = strings[text_id]
        else:
            raise ValueError(f"i18n::TextId::{text_id} ({c_name}) has no _Def in Default.cpp")
        lines.append(f"    {python_constant_name(c_name)}: {label!r},")
    lines.append("}")
    return lines


def write_or_check(path: Path, content: str, check: bool) -> bool:
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if current == content:
        return True
    if check:
        print(f"out of date: {path}", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")
    print(f"generated: {path}")
    return True


def default_source_root(repo_root: Path) -> Path:
    configured = os.environ.get("MDR_SOURCE_DIR")
    if configured:
        return Path(configured)
    return repo_root.parent / "SonyHeadphonesClient"


def main() -> int:
    repo_root = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source",
        type=Path,
        default=default_source_root(repo_root),
        help="SonyHeadphonesClient checkout (default: MDR_SOURCE_DIR or sibling checkout)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=repo_root / "libmdr" / "src" / "libmdr",
        help="libmdr Python package directory",
    )
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()

    source = args.source.resolve()
    include = source / "libmdr" / "include" / "mdr-c"
    paths = [include / name for name in ("Base.h", "Connection.h", "Headphones.h")]
    paths += [source / "client" / "Client.cpp", source / "client" / "I18N" / "Default.cpp"]
    missing = [path for path in paths if not path.is_file()]
    if missing:
        parser.error("missing source file(s): " + ", ".join(str(path) for path in missing))
    base, connection, headphones, client, strings = [path.read_text(encoding="utf-8") for path in paths]

    outputs = {
        args.output / "_generated_api.py": render_api([base, connection, headphones]),
        args.output / "_generated_constants.py": render_constants(
            headphones,
            trailer=render_feature_names(headphones, client, strings),
        ),
        args.output / "_generated_result.py": render_constants(base, results=True),
    }
    # NB: not all(...) -- that short-circuits and would only report the first
    # stale file under --check.
    ok = [write_or_check(path, content, args.check) for path, content in outputs.items()]
    return 0 if all(ok) else 1


if __name__ == "__main__":
    raise SystemExit(main())
